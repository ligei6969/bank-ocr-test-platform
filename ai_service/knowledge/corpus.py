def _doc(
    doc_id: str,
    title: str,
    category: str,
    content: str,
    *,
    tags: Sequence[str] = (),
) -> KnowledgeDoc:
    return KnowledgeDoc(
        doc_id=doc_id,
        title=title,
        category=category,
        content=content,
        reason_codes=(),
        doc_types=(DOC_TYPE_ANY,),
        tags=tuple(tags),
    )


