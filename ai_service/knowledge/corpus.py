"""客服知识语料：业务规则、材料清单、办理流程、合规口径。

定位
----
与 ``ai_service/corpus.py``（审核原因码语料）**并列**，不混在一起：

* 审核语料服务的是「解释一条记录」，带原因码，面向审核员；
* 本语料服务的是「回答一个业务问题」，面向平台用户与客户经理。

两者共用 :class:`ai_service.corpus.KnowledgeDoc` 与检索层，但语料本身不重叠 ——
混在一起会让检索在错误的域里召回（用户问「二类户要什么材料」，
却召回一堆 ``image_blur`` 的处置建议）。

内容是示例，不是行内制度
------------------------
以下条目是按公开、通用的银行业务常识写的**示例语料**，用来演示与测试
「答案必须有出处」这条约束。它们**不是任何一家银行的正式制度**，
也刻意不写具体费率、利率、额度 —— 那类数字会随政策与产品变化，
写进语料就等于制造一个一定会过期的事实源。

真实落地时把本文件替换成行内知识库的导入即可，接口不变。
"""

